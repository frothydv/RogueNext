// Compresses the raw Blender glTF exports (assets/raw/*.glb) into assets/models/*.glb using
// meshopt + quantization, and writes src/render/assets.generated.js so esbuild inlines them.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { EXTMeshoptCompression, KHRMeshQuantization, KHRMaterialsEmissiveStrength } from '@gltf-transform/extensions';
import { quantize, meshopt, dedup, prune, weld } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rawDir = path.join(root, 'assets/raw'), outDir = path.join(root, 'assets/models');
fs.mkdirSync(outDir, { recursive: true });
await MeshoptEncoder.ready; await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions([EXTMeshoptCompression, KHRMeshQuantization, KHRMaterialsEmissiveStrength])
  .registerDependencies({ 'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });

let total = 0;
for (const f of fs.readdirSync(rawDir).filter((n) => n.endsWith('.glb'))) {
  const doc = await io.read(path.join(rawDir, f));
  await doc.transform(dedup(), weld({ tolerance: 0.00002 }), prune(), meshopt({ encoder: MeshoptEncoder, level: 'high' }));
  const out = path.join(outDir, f);
  await io.write(out, doc);
  const a = fs.statSync(path.join(rawDir, f)).size, b = fs.statSync(out).size;
  total += b;
  console.log(`${f.padEnd(22)} ${(a / 1024).toFixed(0).padStart(6)} KB -> ${(b / 1024).toFixed(0).padStart(6)} KB`);
}
// generated import list
const names = fs.readdirSync(outDir).filter((n) => n.endsWith('.glb')).sort();
let js = '// GENERATED by scripts/optimize.mjs — do not edit\n';
names.forEach((n, i) => { js += `import m${i} from '../../assets/models/${n}';\n`; });
js += `export const MODEL_DATA = {\n${names.map((n, i) => `  '${n.replace('.glb', '')}': m${i},`).join('\n')}\n};\n`;
fs.writeFileSync(path.join(root, 'src/render/assets.generated.js'), js);
console.log(`total ${(total / 1024).toFixed(0)} KB in ${names.length} models`);
